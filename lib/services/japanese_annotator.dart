/// 日语歌词辅助引擎：将日文文本中的汉字标注平假名读音，并给出中文释义。
///
/// 这是「日语歌词辅助」功能的核心，纯离线运行：
/// - 内置常用日文汉字 → 读音（平假名）映射表
/// - 内置常用词 → 中文释义映射表
/// - 对每个汉字/词素做逐字扫描，生成注音+释义列表
class JapaneseAnnotator {
  JapaneseAnnotator._();

  static final JapaneseAnnotator _instance = JapaneseAnnotator._();
  static JapaneseAnnotator get instance => _instance;

  /// 是否为日文歌词（启发式：包含假名或日文汉字）。
  bool isJapanese(String text) {
    for (final c in text.runes) {
      if (c >= 0x3040 && c <= 0x30FF) return true; // 平假名/片假名
      if (c >= 0x4E00 && c <= 0x9FFF) return true; // 汉字（含日文汉字）
    }
    return false;
  }

  /// 对整句歌词做注音+释义标注。
  ///
  /// 算法：
  /// 1. 先尝试最长匹配多字词（如「読む」「勉強」等），降低单字歧义；
  /// 2. 剩余单字用 [singleKanjiReadings] 注音；
  /// 3. 假名本身原样保留，不标注。
  List<RubyAnnotation> annotate(String text) {
    if (!isJapanese(text)) return const [];
    final result = <RubyAnnotation>[];
    final chars = text.runes.toList();
    int i = 0;

    while (i < chars.length) {
      final ch = String.fromCharCode(chars[i]);

      // 尝试多字词匹配（2字优先，最长匹配）
      int bestLen = 0;
      String? bestReading;
      String? bestMeaning;
      for (int len = _maxWordLength; len >= 2; len--) {
        if (i + len > chars.length) continue;
        final word = String.fromCharCodes(chars.sublist(i, i + len));
        final entry = _wordReadings[word];
        if (entry != null) {
          bestLen = len;
          bestReading = entry;
          bestMeaning = _wordMeanings[word];
          break;
        }
      }

      if (bestLen > 0) {
        final word = String.fromCharCodes(chars.sublist(i, i + bestLen));
        result.add(RubyAnnotation(
          surface: word,
          reading: bestReading!,
          meaning: bestMeaning,
        ));
        i += bestLen;
        continue;
      }

      // 单字注音
      if (_isKanji(chars[i])) {
        final reading = _singleKanjiReadings[ch];
        result.add(RubyAnnotation(
          surface: ch,
          reading: reading ?? ch,
          meaning: _singleKanjiMeanings[ch],
        ));
      } else {
        // 假名、标点等：原样作为一个不可注音单元
        result.add(RubyAnnotation(
          surface: ch,
          reading: ch,
          meaning: null,
        ));
      }
      i++;
    }

    return result;
  }

  static bool _isKanji(int code) =>
      (code >= 0x4E00 && code <= 0x9FFF) ||
      (code >= 0x3400 && code <= 0x4DBF);

